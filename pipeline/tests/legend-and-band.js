const fs=require('fs'),{JSDOM}=require('jsdom');
const html=fs.readFileSync(require('path').join(__dirname,'..','..','index.html'),'utf8');
const dom=new JSDOM(html,{url:'http://localhost/',runScripts:'dangerously',pretendToBeVisual:true,beforeParse(w){
 w.matchMedia=q=>({matches:false,addEventListener(){},addListener(){}});
 Object.defineProperty(w.HTMLElement.prototype,'clientWidth',{get(){return 1600}});
 Object.defineProperty(w.HTMLElement.prototype,'clientHeight',{get(){return 900}});}});
setTimeout(()=>{const w=dom.window,d=w.document,fail=[];
 const b=()=>w.eval('BOX');
 console.log('legend class on body at boot:', d.body.className || '(none)');
 if(d.body.classList.contains('legend')) fail.push('legend visible by default');
 const b1=b(); console.log('map bottom without legend:', b1.B.toFixed(0), '(window 844)');
 d.getElementById('btnFoot').dispatchEvent(new w.MouseEvent('click',{bubbles:true}));
 const b2=b(); console.log('after Legend click: body =', d.body.className, '| map bottom', b2.B.toFixed(0));
 if(!d.body.classList.contains('legend')) fail.push('Legend button did not switch it on');
 if(b1.B - b2.B !== 72) fail.push('map did not reclaim the 72px legend panel (delta '+(b1.B-b2.B)+')');
 const bar=d.getElementById('colBar');
 const css=[...d.querySelectorAll('style')].map(x=>x.textContent).join('');
 const rule=css.match(/\.colbar\{[^}]*\}/)[0];
 console.log('band:', rule.replace(/\s+/g,' '));
 if(/var\(--bg\)/.test(rule)) fail.push('band still painted with an undefined variable');
 if(!/background:var\(--paper\)/.test(rule)) fail.push('band has no opaque background');
 const zBar=+rule.match(/z-index:(\d+)/)[1], zCan=+css.match(/\.canvas\{[^}]*\}/)[0].match(/z-index:(\d+)/)[1];
 console.log('z-index band', zBar, '> canvas', zCan);
 if(zBar<=zCan) fail.push('band is not above the canvas');
 console.log(fail.length?'\nFAIL:\n - '+fail.join('\n - '):'\nALL PASS'); if(fail.length) process.exitCode = 1;
},700);
